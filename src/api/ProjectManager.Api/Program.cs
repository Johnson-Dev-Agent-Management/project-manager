using Microsoft.EntityFrameworkCore;
using ProjectManager.Api;
var builder = WebApplication.CreateBuilder(args);
builder.Services.AddDbContext<ProjectDb>(options => options.UseSqlite(builder.Configuration.GetConnectionString("Projects") ?? "Data Source=projects.db"));
var app = builder.Build();
using (var scope = app.Services.CreateScope()) DatabaseSchema.Initialize(scope.ServiceProvider.GetRequiredService<ProjectDb>());
app.MapGet("/api/health", () => Results.Ok(new { status = "ok" }));
app.MapProjects();
app.MapMilestones();
app.MapToday();
app.MapInbox();
app.Run();
